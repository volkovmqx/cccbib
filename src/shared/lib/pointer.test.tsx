import { renderHook } from '@testing-library/react';
import { expect, test, vi } from 'vitest';
import { isPointerDriven, pointerMoved, useWheelNavigation } from './pointer';

const at = (clientX: number, clientY: number) => ({ nativeEvent: new Event('mousemove'), clientX, clientY });

test('a pointer move is recognised once per event and repeats at the same position are ignored', () => {
  expect(pointerMoved(at(5, 5))).toBe(true);
  expect(pointerMoved(at(5, 5))).toBe(false);
  const moved = at(9, 5);
  expect(pointerMoved(moved)).toBe(true);
  expect(pointerMoved(moved)).toBe(true);
  expect(pointerMoved(at(9, 6))).toBe(true);
});

test('the wheel steps through the focused list like the up and down keys, one step at a time, but not over the player', () => {
  vi.useFakeTimers();
  vi.setSystemTime(1000);
  const keys: string[] = [];
  const listener = (event: KeyboardEvent) => keys.push(event.key);
  window.addEventListener('keydown', listener);
  const { unmount } = renderHook(() => useWheelNavigation());
  const wheel = (deltaY: number, target: Element = document.body) => {
    const event = new WheelEvent('wheel', { deltaY, bubbles: true, cancelable: true });
    target.dispatchEvent(event);
    return event;
  };
  expect(wheel(100).defaultPrevented).toBe(true);
  expect(wheel(100).defaultPrevented).toBe(true);
  vi.advanceTimersByTime(130);
  wheel(-100);
  expect(keys).toEqual(['ArrowDown', 'ArrowUp']);
  vi.advanceTimersByTime(130);
  expect(wheel(0).defaultPrevented).toBe(false);
  const player = document.createElement('div');
  player.className = 'player-wrapper';
  const picker = document.createElement('div');
  picker.className = 'picker';
  player.append(picker);
  document.body.append(player);
  expect(wheel(100, player).defaultPrevented).toBe(false);
  expect(wheel(100, picker).defaultPrevented).toBe(true);
  expect(keys).toEqual(['ArrowDown', 'ArrowUp', 'ArrowDown']);
  const page = document.createElement('div');
  page.setAttribute('data-wheel', 'scroll');
  const row = document.createElement('div');
  page.append(row);
  document.body.append(page);
  vi.advanceTimersByTime(130);
  expect(wheel(100, row).defaultPrevented).toBe(false);
  expect(keys).toEqual(['ArrowDown', 'ArrowUp', 'ArrowDown']);
  page.remove();
  unmount();
  vi.advanceTimersByTime(130);
  expect(wheel(100).defaultPrevented).toBe(false);
  window.removeEventListener('keydown', listener);
  player.remove();
});

test('a popup scrolls its own list from anywhere over it instead of stepping through it, and leaves the wheel over the list to the browser', () => {
  vi.useFakeTimers();
  const keys: string[] = [];
  const listener = (event: KeyboardEvent) => keys.push(event.key);
  window.addEventListener('keydown', listener);
  const picker = document.createElement('div');
  picker.className = 'picker';
  const title = document.createElement('h3');
  const list = document.createElement('div');
  list.className = 'picker__list';
  list.setAttribute('data-wheel', 'scroll');
  const item = document.createElement('div');
  list.append(item);
  picker.append(title, list);
  document.body.append(picker);
  const { unmount } = renderHook(() => useWheelNavigation());
  const wheel = (deltaY: number, target: Element, deltaMode = 0) => {
    const event = new WheelEvent('wheel', { deltaY, deltaMode, bubbles: true, cancelable: true });
    target.dispatchEvent(event);
    return event;
  };
  expect(wheel(100, item).defaultPrevented).toBe(false);
  expect(list.scrollTop).toBe(0);
  expect(wheel(100, title).defaultPrevented).toBe(true);
  expect(list.scrollTop).toBe(100);
  expect(wheel(-30, picker).defaultPrevented).toBe(true);
  expect(list.scrollTop).toBe(70);
  wheel(3, title, 1);
  expect(list.scrollTop).toBe(190);
  expect(keys).toEqual([]);
  unmount();
  vi.advanceTimersByTime(300);
  window.removeEventListener('keydown', listener);
  picker.remove();
});

test('a page that scrolls under a resting cursor hands the hover to the element that arrived below it', () => {
  vi.useFakeTimers();
  const page = document.createElement('div');
  page.setAttribute('data-wheel', 'scroll');
  const row = document.createElement('div');
  page.append(row);
  document.body.append(page);
  const below = vi.fn(() => row);
  Object.defineProperty(document, 'elementFromPoint', { configurable: true, value: below });
  const seen: boolean[] = [];
  row.addEventListener('mousemove', (event) => seen.push(pointerMoved({ nativeEvent: event, clientX: event.clientX, clientY: event.clientY })));
  pointerMoved(at(40, 50));
  const { unmount } = renderHook(() => useWheelNavigation());
  page.dispatchEvent(new WheelEvent('wheel', { deltaY: 100, bubbles: true, cancelable: true }));
  expect(seen).toEqual([]);
  vi.advanceTimersByTime(100);
  expect(seen).toEqual([true]);
  expect(below).toHaveBeenCalledWith(40, 50);
  page.dispatchEvent(new WheelEvent('wheel', { deltaY: 100, bubbles: true, cancelable: true }));
  vi.advanceTimersByTime(250);
  expect(seen).toEqual([true, true, true]);
  below.mockReturnValue(null as never);
  page.dispatchEvent(new WheelEvent('wheel', { deltaY: 100, bubbles: true, cancelable: true }));
  vi.advanceTimersByTime(250);
  expect(seen).toHaveLength(3);
  below.mockReturnValue(row);
  page.dispatchEvent(new WheelEvent('wheel', { deltaY: 100, bubbles: true, cancelable: true }));
  unmount();
  vi.advanceTimersByTime(250);
  expect(seen).toHaveLength(3);
  Reflect.deleteProperty(document, 'elementFromPoint');
  page.remove();
});

test('a wheel notch over the navigation bar opens the menu before it steps through it', () => {
  vi.useFakeTimers();
  vi.setSystemTime(5000);
  const nav = document.createElement('nav');
  nav.className = 'appShell__nav';
  document.body.append(nav);
  const keys: string[] = [];
  const listener = (event: KeyboardEvent) => keys.push(event.key);
  window.addEventListener('keydown', listener);
  let open = false;
  const openMenu = vi.fn(() => { if (open) return false; open = true; return true; });
  renderHook(() => useWheelNavigation(openMenu));
  const wheel = (target: Element) => target.dispatchEvent(new WheelEvent('wheel', { deltaY: 100, bubbles: true, cancelable: true }));
  wheel(nav);
  expect(keys).toEqual([]);
  expect(openMenu).toHaveBeenCalledTimes(1);
  vi.advanceTimersByTime(130);
  wheel(nav);
  expect(keys).toEqual(['ArrowDown']);
  vi.advanceTimersByTime(130);
  wheel(document.body);
  expect(keys).toEqual(['ArrowDown', 'ArrowDown']);
  expect(openMenu).toHaveBeenCalledTimes(2);
  window.removeEventListener('keydown', listener);
  nav.remove();
});

test('the wheel over the preview and the list headers scrolls the main region of the page instead of stepping the selection', () => {
  vi.useFakeTimers();
  vi.setSystemTime(9000);
  const keys: string[] = [];
  const listener = (event: KeyboardEvent) => keys.push(event.key);
  window.addEventListener('keydown', listener);
  const main = document.createElement('div');
  main.setAttribute('data-wheel', 'scroll');
  main.setAttribute('data-wheel-main', '');
  const header = document.createElement('div');
  const nav = document.createElement('nav');
  nav.className = 'appShell__nav';
  const picker = document.createElement('div');
  picker.className = 'picker';
  document.body.append(main, header, nav, picker);
  Object.defineProperty(document, 'elementFromPoint', { configurable: true, value: () => null });
  const { unmount } = renderHook(() => useWheelNavigation());
  const wheel = (target: Element, deltaY: number, deltaMode = 0) => {
    const event = new WheelEvent('wheel', { deltaY, deltaMode, bubbles: true, cancelable: true });
    target.dispatchEvent(event);
    return event;
  };
  expect(wheel(header, 120).defaultPrevented).toBe(true);
  expect(main.scrollTop).toBe(120);
  expect(wheel(header, 3, 1).defaultPrevented).toBe(true);
  expect(main.scrollTop).toBe(240);
  expect(wheel(main, 100).defaultPrevented).toBe(false);
  expect(main.scrollTop).toBe(240);
  expect(keys).toEqual([]);
  vi.advanceTimersByTime(300);
  wheel(nav, 100);
  wheel(picker, 100);
  expect(main.scrollTop).toBe(240);
  expect(keys).toEqual(['ArrowDown']);
  vi.advanceTimersByTime(130);
  wheel(picker, 100);
  expect(keys).toEqual(['ArrowDown', 'ArrowDown']);
  unmount();
  Reflect.deleteProperty(document, 'elementFromPoint');
  window.removeEventListener('keydown', listener);
  main.remove(); header.remove(); nav.remove(); picker.remove();
});

test('a selection that follows the pointer is flagged until the next key press', () => {
  const { unmount } = renderHook(() => useWheelNavigation());
  pointerMoved(at(700, 700));
  expect(isPointerDriven()).toBe(true);
  window.dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowDown' }));
  expect(isPointerDriven()).toBe(false);
  pointerMoved(at(700, 700));
  expect(isPointerDriven()).toBe(false);
  pointerMoved(at(701, 700));
  expect(isPointerDriven()).toBe(true);
  unmount();
});
